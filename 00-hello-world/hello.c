/*
 * 预处理指令：以 # 开头，在编译之前由预处理器处理。
 *
 * 这一行把标准库头文件 stdio.h 的内容“复制”到此处，
 * 使编译器在此后知道 printf 的声明。
 *
 * 注意：预处理指令不以分号结尾。
 */
#include <stdio.h>

/*
 * 函数定义：
 *
 *     int main(void)
 *
 *   int    返回类型：main 把整数结果交给运行环境
 *   main   函数名：C 标准约定的程序入口
 *   void   参数列表：表示 main 不接受参数
 *
 *  main 不是关键字，而是 C 标准约定的入口函数名。
 *  C 区分大小写：Main、MAIN 都不是 main。
 */
int main(void)
{
    /*
     * 函数调用表达式语句：
     *
     *     printf("Hello, World!\n");
     *
     *   printf                被调用的函数
     *   ("Hello, World!\n")   参数列表，其中是一个字符串字面量
     *   ;                     表达式语句的结束
     *
     * "\n" 是一个转义序列，表示换行符。
     * 它在字符串中只占一个字符，不是反斜杠加字母 n。
     */
    printf("Hello, World!\n");

    /*
     * return 语句：结束 main，并把 0 返回给运行环境。
     *
     * 0 表示程序正常结束；非 0 通常表示失败。
     * 在 C99 及之后，main 执行到右花括号时也会隐式返回 0，
     * 但显式写出来更清楚。
     */
    return 0;
}
